PERSIAN_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
ARABIC_SEPARATOR = "\u066b"          # ٫ the decimal separator used in the assignment


def fa_number(number: str) -> str:
    """8.3 -> ۸٫۳ (section and item separated by U+066B, not a dot)."""
    return number.translate(PERSIAN_DIGITS).replace(".", ARABIC_SEPARATOR)


def markdown(source: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": source.splitlines(keepends=True)}


def code(source: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": source.splitlines(keepends=True)}


# ------------------------------------------------------------------ analysis text
def _conceptual_analysis(qid: str) -> str:
    """Persian analysis for a conceptual question, quoting the chosen option and reason."""
    text = ANSWERS_DOC.read_text(encoding="utf-8")
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and cells[0] == qid:
            option = cells[2].replace("**", "")
            reason = cells[3].replace("**", "")
            return (
                f"**تحلیل.** گزینهٔ انتخاب‌شده **{option}** است.\n\n"
                f"{reason}\n\n"
                "این زیرسؤال مفهومی است و داده‌ای مصرف نمی‌کند؛ معیار درست‌بودن، تطبیق گزینه با "
                "قید مسئله است، نه تعریف عمومی. وزن تصحیح ۶۰٪ گزینه و ۴۰٪ دلیل است، پس دلیل باید "
                "به همان قیدی اشاره کند که در صورت سؤال آمده.\n"
            )
    return "**تحلیل.** پاسخ این زیرسؤال در کارنامهٔ پاسخ‌های مفهومی ثبت شده است.\n"


